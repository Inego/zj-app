package inego.zungjunggame.arch

import java.io.File
import kotlin.test.Test
import kotlin.test.assertTrue
import kotlin.test.fail

/**
 * Nothing the *build* produces may enter the asset tree without a decision.
 *
 * ### What happened
 *
 * `Fonts` wrote a font diagnostic through `Gdx.files.local`. On desktop that is
 * the working directory, and `lwjgl3/build.gradle` sets the working directory to
 * the **staged assets dir** — so the app wrote its log *into the asset tree it was
 * running from*, once a second, with a sparse CPU pixel-scan in the loop.
 *
 * The file was `.gitignore`d, so it never appeared in review. `.gitignore` has no
 * effect on Gradle: `stageAssets` copies `assets/` wholesale, so the log was
 * re-staged on every build and had reached **11 MB / 128,837 lines** — inside the
 * release APK (4.7 MB raw, 205 KB compressed), the debug APK, and the web preload
 * manifest. It was being copied to production by a deploy.
 *
 * The writer is gone (2026-09-29) and `stageAssets` now excludes the file, but
 * neither fact is self-enforcing. A future diagnostic that writes to
 * `Gdx.files.local` would do it again, and an `exclude` line is the kind of thing
 * that gets tidied away as cruft.
 *
 * ### Why this is a test and not a code review note
 *
 * Nothing in the Kotlin architecture ratchet covers this — it governs source
 * imports, not build inputs. So the failure mode has no guard at all, and it
 * produces a *green build* every time. These checks make it loud instead.
 *
 * ### The rule
 *
 * The asset tree holds authored assets only. A file that appears there but is
 * neither tracked by git nor deliberately generated is debris that has escaped
 * into a shipping input, and it is reported rather than ignored.
 */
class StagedAssetPurityTest {

    // `cwd` for `:core:test` is `core`, so the repo root is one level up.
    private val repoRoot = File("..")
    private val assetsDir = File(repoRoot, "assets")

    /**
     * Files the build legitimately writes into `assets/`.
     *
     * `assets.txt` is generated by `:generateAssetList` and is itself gitignored
     * for the same reason a diagnostic would be: it is an output, not an input.
     * It is small, regenerated on every build, and excluded from `stageAssets` too.
     */
    private val generatedInAssets = setOf("assets.txt")

    @Test
    fun `the asset tree holds no untracked debris`() {
        assertTrue(assetsDir.isDirectory, "expected assets/ at ${assetsDir.absolutePath}")

        val tracked = trackedAssetFiles()
        val debris = assetsDir.walkTopDown()
            .filter { it.isFile }
            .map { assetsDir.toPath().relativize(it.toPath()).toString().replace('\\', '/') }
            .filterNot { tracked.contains(it) }
            .filterNot { generatedInAssets.contains(it) }
            .toList()
            .sorted()

        if (debris.isNotEmpty()) {
            fail(
                buildString {
                    appendLine(
                        "${debris.size} untracked file(s) in assets/ that the build would stage and ship.",
                    )
                    appendLine("cwd=${File(".").absolutePath}")
                    appendLine()
                    debris.forEach { appendLine("  $it") }
                    appendLine()
                    appendLine("assets/ is a build INPUT: stageAssets copies it wholesale into the")
                    appendLine("desktop jar, the APK and the web preload manifest. A .gitignore entry")
                    appendLine("does not stop any of that — gitignore governs git, not Gradle.")
                    appendLine()
                    appendLine("Either the file is debris and should be deleted, or it is generated")
                    appendLine("and belongs in $generatedInAssets with an exclude in")
                    appendLine("core/build.gradle's stageAssets task.")
                },
            )
        }
    }

    @Test
    fun `stageAssets excludes every generated file it also leaves in the asset tree`() {
        // A generated file has to be excluded twice over: once so it is not
        // staged, and once so it is not listed. assets.txt and lang/ already are.
        // font-diag.txt is the case that motivated this test and is belt-and-braces
        // now that its writer is gone — if someone deletes the exclude line, a stale
        // copy in a working tree would go straight back into the APK.
        val buildGradle = File(repoRoot, "core/build.gradle")
        assertTrue(buildGradle.isFile, "expected core/build.gradle at ${buildGradle.absolutePath}")
        val text = buildGradle.readText()

        val stageAssets = text.substringAfter("tasks.register('stageAssets'")
        val block = stageAssets.substringBefore("tasks.register(")
        assertTrue(block.isNotEmpty(), "could not find the stageAssets task body in core/build.gradle")

        for (generated in generatedInAssets + "font-diag.txt") {
            assertTrue(
                block.contains("exclude '$generated'"),
                "stageAssets must exclude '$generated'.\n" +
                    "A gitignored file in assets/ is still copied by `from(rootProject.file('assets'))`, " +
                    "so without the exclude it reaches the release APK and the web preload manifest.",
            )
        }
    }

    @Test
    fun `no font diagnostic writer remains`() {
        // The writer itself. Pinned rather than left to the compiler because
        // `Gdx.files.local(...)` is a valid call that compiles forever, and
        // nothing else in the tree would notice it reappearing.
        val offenders = listOf(
            File(repoRoot, "core/src/main/kotlin/inego/zungjunggame/render/fonts/Fonts.kt"),
            File(repoRoot, "core/src/main/kotlin/inego/zungjunggame/Main.kt"),
            File(repoRoot, "core/src/main/kotlin/inego/zungjunggame/app/AppRuntime.kt"),
        ).filter { file ->
            file.isFile && Regex("""font-diag\.txt|writeLocalDiag|diagHeartbeat|resetDiagFile""")
                .containsMatchIn(file.readText())
        }.map { it.name }

        assertTrue(
            offenders.isEmpty(),
            "the font diagnostic was removed 2026-09-29; it wrote into the asset tree at " +
                "1 Hz and reached 11 MB in the shipped APK. Still referenced in: $offenders",
        )
    }

    /** Asset-relative paths git knows about, so build outputs are not debris. */
    private fun trackedAssetFiles(): Set<String> {
        val proc = ProcessBuilder(
            "git", "-C", repoRoot.absolutePath, "ls-files", "--", "assets",
        ).redirectErrorStream(true).start()
        val out = proc.inputStream.bufferedReader().readText()
        proc.waitFor()
        return out.lines()
            .filter { it.isNotBlank() }
            .map { it.removePrefix("assets/") }
            .toSet()
    }
}
